"""Curriculum Schema Validation Suite for LLM-Generated Content (Roadmap Sec. 27).

Validates curriculum JSON structures generated by LLMs before acceptance:
1. Root object contains required fields: 'module_id', 'title', 'concepts'.
2. Concepts is a non-empty list of concepts.
3. Every concept has 'concept_id', 'name', 'prerequisites', 'difficulty', 'questions'.
4. concept_id values are non-empty strings and unique within the module.
5. Difficulty is an integer in [1, 5].
6. Every prerequisite reference points to a valid concept_id defined within the module.
7. No concept references itself as a prerequisite, and no circular dependencies exist.
8. Each question has non-empty 'question_id', 'prompt', 'answer', and valid 'type' ('mcq' | 'short' | 'code').
"""

import json
from typing import Any

ALLOWED_QUESTION_TYPES = {"mcq", "short", "code"}


def validate_curriculum_json(data: dict[str, Any] | str) -> tuple[bool, list[str]]:
    """Validate a parsed dictionary or raw JSON string against the curriculum schema.

    Returns:
        (is_valid: bool, errors: list[str])
    """
    errors: list[str] = []

    # 1. Parse JSON if string is provided
    if isinstance(data, str):
        text = data.strip()
        # Clean markdown code fences if LLM wrapped output in ```json ... ```
        if text.startswith("```"):
            lines = text.splitlines()
            if lines[0].startswith("```"):
                lines = lines[1:]
            if lines and lines[-1].strip().startswith("```"):
                lines = lines[:-1]
            text = "\n".join(lines).strip()

        try:
            parsed = json.loads(text)
        except json.JSONDecodeError as e:
            return False, [f"Invalid JSON syntax: {e}"]
    elif isinstance(data, dict):
        parsed = data
    else:
        return False, [f"Expected JSON object or string, got {type(data).__name__}"]

    if not isinstance(parsed, dict):
        return False, ["Root JSON value must be an object/dict"]

    # 2. Check root-level required fields
    for root_field in ["module_id", "title", "concepts"]:
        if root_field not in parsed:
            errors.append(f"Missing required root field '{root_field}'")

    if errors:
        return False, errors

    module_id = str(parsed["module_id"]).strip()
    title = str(parsed["title"]).strip()
    concepts = parsed["concepts"]

    if not module_id:
        errors.append("Root 'module_id' must not be empty")
    if not title:
        errors.append("Root 'title' must not be empty")
    if not isinstance(concepts, list) or len(concepts) == 0:
        errors.append("Root 'concepts' must be a non-empty list of concepts")
        return False, errors

    # 3. Check concepts and collect concept_ids
    seen_concept_ids: set[str] = set()
    concept_map: dict[str, dict[str, Any]] = {}

    for idx, c in enumerate(concepts):
        if not isinstance(c, dict):
            errors.append(f"Concept at index {idx} must be an object/dict")
            continue

        cid = c.get("concept_id")
        if not cid or not isinstance(cid, str) or not cid.strip():
            errors.append(f"Concept at index {idx} has missing or empty 'concept_id'")
            continue

        cid = cid.strip()
        if cid in seen_concept_ids:
            errors.append(f"Duplicate 'concept_id' detected: '{cid}'")
        seen_concept_ids.add(cid)
        concept_map[cid] = c

        # Validate name
        cname = c.get("name")
        if not cname or not isinstance(cname, str) or not cname.strip():
            errors.append(f"Concept '{cid}' has missing or empty 'name'")

        # Validate difficulty
        diff = c.get("difficulty")
        if diff is None or not isinstance(diff, (int, float)) or not (1 <= int(diff) <= 5):
            errors.append(f"Concept '{cid}' difficulty must be an integer between 1 and 5 (got {diff})")

        # Validate questions
        questions = c.get("questions")
        if not isinstance(questions, list) or len(questions) == 0:
            errors.append(f"Concept '{cid}' must have a non-empty 'questions' list")
        else:
            seen_qids: set[str] = set()
            for q_idx, q in enumerate(questions):
                if not isinstance(q, dict):
                    errors.append(f"Question {q_idx} in concept '{cid}' must be an object")
                    continue

                qid = q.get("question_id")
                if not qid or not isinstance(qid, str) or not qid.strip():
                    errors.append(f"Question {q_idx} in concept '{cid}' has missing or empty 'question_id'")
                else:
                    if qid in seen_qids:
                        errors.append(f"Duplicate question_id '{qid}' in concept '{cid}'")
                    seen_qids.add(qid)

                prompt = q.get("prompt")
                if not prompt or not isinstance(prompt, str) or not prompt.strip():
                    errors.append(f"Question '{qid or q_idx}' in concept '{cid}' has empty 'prompt'")

                answer = q.get("answer")
                if answer is None or (isinstance(answer, str) and not answer.strip()):
                    errors.append(f"Question '{qid or q_idx}' in concept '{cid}' has empty 'answer'")

                q_type = q.get("type")
                if q_type not in ALLOWED_QUESTION_TYPES:
                    errors.append(
                        f"Question '{qid or q_idx}' in concept '{cid}' has invalid type '{q_type}'. "
                        f"Allowed types are: {sorted(list(ALLOWED_QUESTION_TYPES))}"
                    )

    # 4. Validate prerequisite references and detect cycles
    for cid, c in concept_map.items():
        prereqs = c.get("prerequisites", [])
        if not isinstance(prereqs, list):
            errors.append(f"Prerequisites for concept '{cid}' must be a list")
            continue

        for p in prereqs:
            if not isinstance(p, str) or not p.strip():
                errors.append(f"Concept '{cid}' has empty prerequisite reference")
            elif p == cid:
                errors.append(f"Concept '{cid}' references itself as a prerequisite")
            elif p not in seen_concept_ids:
                errors.append(f"Concept '{cid}' references unknown prerequisite '{p}'")

    # Detect cycles in prerequisite graph via DFS
    if not errors:
        visited: dict[str, int] = {}  # 0: unvisited, 1: visiting, 2: visited

        def has_cycle(node: str) -> bool:
            visited[node] = 1
            for neighbor in concept_map[node].get("prerequisites", []):
                if neighbor in concept_map:
                    if visited.get(neighbor, 0) == 1:
                        return True
                    if visited.get(neighbor, 0) == 0 and has_cycle(neighbor):
                        return True
            visited[node] = 2
            return False

        for node in seen_concept_ids:
            if visited.get(node, 0) == 0:
                if has_cycle(node):
                    errors.append("Circular prerequisite dependency detected in concept graph")
                    break

    is_valid = len(errors) == 0
    return is_valid, errors
